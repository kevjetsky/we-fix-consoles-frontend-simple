export const TIMEZONE = "America/Chicago";

// "3:00 PM" in Houston time.
export function clock(iso) {
  return new Intl.DateTimeFormat("en-US", { timeZone: TIMEZONE, hour: "numeric", minute: "2-digit" }).format(new Date(iso)).replace(/ /g, " ");
}

// "3:00 to 4:00 PM"
export function windowText(startIso, endIso, t) {
  const start = clock(startIso);
  const end = clock(endIso);
  const sameHalf = start.slice(-2) === end.slice(-2);
  return t.windowLabel(sameHalf ? start.replace(/ (AM|PM)$/, "") : start, end);
}

// "Wed Nov 26" / "mié 26 nov"
export function dayText(dateString, lang) {
  const at = new Date(`${dateString}T12:00:00Z`);
  const part = (options) => new Intl.DateTimeFormat(lang === "es" ? "es-US" : "en-US", { timeZone: "UTC", ...options }).format(at).replace(/\.$/, "");
  return lang === "es" ? `${part({ weekday: "short" })} ${part({ day: "numeric" })} ${part({ month: "short" })}` : `${part({ weekday: "short" })} ${part({ month: "short" })} ${part({ day: "numeric" })}`;
}

// "Wednesday, November 26" / "miércoles, 26 de noviembre"
export function longDayText(iso, lang) {
  return new Intl.DateTimeFormat(lang === "es" ? "es-US" : "en-US", { timeZone: TIMEZONE, weekday: "long", month: "long", day: "numeric" }).format(new Date(iso));
}

// Today's date in Houston, YYYY-MM-DD.
export function houstonToday(now = new Date()) {
  return new Intl.DateTimeFormat("en-CA", { timeZone: TIMEZONE, year: "numeric", month: "2-digit", day: "2-digit" }).format(now);
}
